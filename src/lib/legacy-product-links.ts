export function normalizeLegacyAttribute(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/^attribute_/, '').replace(/^pa_/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

export function matchLegacyVariant(
  variants: { id: string; woo_id: number | null; attributes: Record<string,string> }[],
  parameters: URLSearchParams
): { id: string } | null {
  const requested = Array.from(parameters.entries()).filter(([key]) => key.startsWith('attribute_'))
  if (!requested.length) return null
  if (requested.some(([key,value]) => !normalizeLegacyAttribute(key) || !value.trim())) throw new Error('LEGACY_VARIANT_UNKNOWN')
  const matches = variants.filter(variant => requested.every(([key,value]) =>
    Object.entries(variant.attributes || {}).some(([name,option]) => normalizeLegacyAttribute(name) === normalizeLegacyAttribute(key) && normalizeLegacyAttribute(option) === normalizeLegacyAttribute(value))
  ))
  // Partial selections that match multiple variants cannot be redirected precisely.
  if (matches.length !== 1) throw new Error('LEGACY_VARIANT_UNKNOWN')
  return {id:matches[0].woo_id === null ? matches[0].id : String(matches[0].woo_id)}
}
