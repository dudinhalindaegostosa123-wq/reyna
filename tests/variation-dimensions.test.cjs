const {test}=require('node:test'),assert=require('node:assert/strict'),{load}=require('./helpers/load.cjs')
const api=load('src/lib/variation-dimensions.ts'),data=load('src/lib/data.ts')
const row=(id,gauge,length,price,inStock=true)=>({id,name:`Espessuras (Calibre): ${gauge} / Comprimentos da Haste: ${length}`,sku:id,price,priceAvailable:true,stock:null,inStock,image:`/${id}.webp`,attributes:{'Espessuras (Calibre):':gauge,'Comprimentos da Haste:':length}})
const variants=[row('a','1.2 mm','6 mm',50),row('b','1.2 mm','8 mm',55),row('c','1.6 mm','12 mm',60),row('d','1.6 mm','6 mm',61,false)]
test('separate dimensions preserve the real SKU, price, image and availability without manufacturing combinations',()=>{
 const model=api.buildVariationDimensions(variants)
 assert.deepEqual(Array.from(model.fields,field=>field.label),['Espessura (calibre)','Comprimento da haste'])
 let next=api.selectDimension(model,{},'gauge','1.2 mm');assert.equal(next.id,'')
 next=api.selectDimension(model,next.values,'length','8 mm');assert.equal(next.id,'b')
 const selected=data.resolveProductSelection({variations:variants},{Variação:next.id})
 assert.equal(selected.price,55);assert.equal(selected.image,'/b.webp');assert.equal(selected.sku,'b')
 next=api.selectDimension(model,next.values,'gauge','1.6 mm')
 assert.equal(next.id,'');assert.equal(next.values.length,undefined)
 assert.equal(api.dimensionAvailable(model,next.values,'length','8 mm'),false)
 assert.equal(api.dimensionAvailable(model,next.values,'length','6 mm'),false)
 assert.equal(api.dimensionAvailable(model,next.values,'length','12 mm'),true)
 next=api.selectDimension(model,next.values,'length','12 mm');assert.equal(next.id,'c')
 assert.equal(data.resolveProductSelection({variations:variants},{Variação:next.id}).price,60)
 assert.equal(api.dimensionLabel('1.2mm'),'1,2 mm')
})
test('links with a selected variation restore dimensions, extra attributes remain necessary and ambiguous data falls back',()=>{
 const model=api.buildVariationDimensions(variants)
 assert.equal(api.dimensionValues(model,'c').gauge,'1.6 mm')
 assert.equal(api.dimensionValues(model,'c').length,'12 mm')
 const colors=[{...variants[0],attributes:{...variants[0].attributes,'Cor da pedra':'Azul'}},{...variants[0],id:'e',attributes:{...variants[0].attributes,'Cor da pedra':'Verde'}}]
 const colorModel=api.buildVariationDimensions(colors)
 let next=api.selectDimension(colorModel,{},'gauge','1.2 mm')
 next=api.selectDimension(colorModel,next.values,'length','6 mm');assert.equal(next.id,'')
 next=api.selectDimension(colorModel,next.values,colorModel.fields[2].key,'Verde');assert.equal(next.id,'e')
 assert.equal(api.buildVariationDimensions([variants[0],{...variants[0],id:'duplicate'}]),null)
 assert.equal(api.buildVariationDimensions([{...variants[0],attributes:undefined}]),null)
 assert.equal(api.buildVariationDimensions([variants[0],{...variants[1],attributes:{Espessura:'1.2 mm'}}]),null)
 const irrelevant=api.buildVariationDimensions([{...variants[0],attributes:{'Comprimento da pedra':'6 mm','Rosca interna':'1.2 mm'}}])
 assert.equal(irrelevant,null)
})
