const {test}=require('node:test'),assert=require('node:assert/strict'),{load}=require('./helpers/load.cjs')
const {legacySearch,legacySearchFilter,legacyHistoryHref}=load('src/lib/legacy-history-search.ts')
test('legacy search combines separate first and last names and preserves the search during pagination and detail navigation',()=>{
 const search=legacySearch('  Nicole   Barros  ')
 const filter=legacySearchFilter(search)
 assert.match(filter,/^and\(or\(/)
 assert.match(filter,/payload->>primeiro_nome.ilike.%Nicole%/)
 assert.match(filter,/payload->>sobrenome.ilike.%Barros%/)
 const href=new URL(legacyHistoryHref({search,page:2,order:'24420'}),'https://fixture.example')
 assert.equal(href.searchParams.get('q'),'Nicole Barros');assert.equal(href.searchParams.get('page'),'2');assert.equal(href.searchParams.get('pedido'),'24420')
 assert.equal(legacySearchFilter('24420'),'old_id.eq.24420')
 assert.match(legacySearchFilter('11999999999',true),/phone.ilike.%11999999999%/)
 assert.match(legacySearchFilter('Paula',true),/name.ilike.%Paula%/)
 assert.equal(new URL(legacyHistoryHref({search,customers:true}),'https://fixture.example').searchParams.get('clientes'),'1')
})
test('legacy search strips PostgREST operators and delimiters from untrusted search text',()=>{
 const search=legacySearch('Ana%,(old_id.gt.0)')
 assert.doesNotMatch(search,/[%(),]/)
 assert.doesNotMatch(legacySearchFilter(search),/or\(old_id.gt.0/)
 assert.equal(legacySearch(undefined),'')
})
