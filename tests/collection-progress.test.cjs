const {test}=require('node:test')
const assert=require('node:assert/strict')
const {load}=require('./helpers/load.cjs')
const {collectionProgressMessage}=load('src/lib/collection-progress.ts')
test('progress notice reflects each eligible jewelry tier, including empty cart and maximum',()=>{
 assert.match(collectionProgressMessage(0),/Faltam 2 joias.*5%/)
 assert.match(collectionProgressMessage(1),/Falta 1 joia.*5%/)
 assert.match(collectionProgressMessage(2),/Falta 1 joia.*7%/)
 assert.match(collectionProgressMessage(3),/Falta 1 joia.*10%/)
 assert.match(collectionProgressMessage(4),/Falta 1 joia.*15%/)
 assert.match(collectionProgressMessage(5),/alcançou 15%/)
 assert.match(collectionProgressMessage(8),/alcançou 15%/)
 assert.equal(collectionProgressMessage(-1),'')
})
