const {test}=require('node:test'),assert=require('node:assert/strict'),{load}=require('./helpers/load.cjs')
const {renderer,nodes}=require('./helpers/render.cjs')
const api=load('src/lib/variation-dimensions.ts')
const rows=[['a','1.2 mm','6 mm'],['b','1.2 mm','8 mm'],['c','1.6 mm','12 mm']].map(([id,gauge,length])=>({id,priceAvailable:true,inStock:true,attributes:{Espessura:gauge,'Comprimento da haste':length}}))
test('two compact controls retain incomplete choices and clear incompatible lengths before selecting another SKU',()=>{
 const model=api.buildVariationDimensions(rows);let selectedId=''
 const view=renderer('src/components/product/DimensionalVariationSelector.tsx',{'@/lib/variation-dimensions':api})
 const props=()=>({model,selectedId,onChange:id=>{selectedId=id}})
 let tree=view.render(props()),selects=nodes(tree,node=>node.type==='select')
 assert.equal(selects.length,2);assert.equal(selects[1].props.disabled,true)
 selects[0].props.onChange({target:{value:'1.2 mm'}})
 tree=view.render(props());selects=nodes(tree,node=>node.type==='select')
 assert.equal(selects[0].props.value,'1.2 mm');assert.equal(selects[1].props.disabled,false);assert.equal(selectedId,'')
 selects[1].props.onChange({target:{value:'8 mm'}});assert.equal(selectedId,'b')
 tree=view.render(props());selects=nodes(tree,node=>node.type==='select')
 selects[0].props.onChange({target:{value:'1.6 mm'}})
 tree=view.render(props());selects=nodes(tree,node=>node.type==='select')
 assert.equal(selectedId,'');assert.equal(selects[1].props.value,'')
 selects[1].props.onChange({target:{value:'12 mm'}});assert.equal(selectedId,'c')
 tree=view.render({...props(),disabled:true})
 assert.ok(nodes(tree,node=>node.type==='select').every(node=>node.props.disabled))
})
